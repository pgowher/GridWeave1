_LAZY_STUDY_RUNNER_EXPORTS = frozenset(
    {
        "StudyExecutionError",
        "execute_factorial_study",
        "planned_study_execution",
    }
)


def __getattr__(name: str):
    """Load the S21 runner without creating an artifacts/experiments cycle."""

    if name not in _LAZY_STUDY_RUNNER_EXPORTS:
        raise AttributeError(name)
    from . import study_runner

    value = getattr(study_runner, name)
    globals()[name] = value
    return value
